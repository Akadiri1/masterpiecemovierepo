<script>
    document.addEventListener("DOMContentLoaded", () => {

  // === 1. Select elements ===
  const loginForm = document.querySelector("#login-form");
  const loginButton = document.querySelector("#login-button");
  const buttonText = loginButton.querySelector(".button-text");
  const loadingSpinner = loginButton.querySelector(".spinner-border");
  const formMessage = document.querySelector("#form-message"); // For "Invalid" errors
  
  const identityInput = document.querySelector("#login-identity");
  const passwordInput = document.querySelector("#login-password");
  const togglePassword = document.querySelector("#togglePassword");

  // === 2. Helper functions ===

  function showError(inputElement, message) {
    inputElement.classList.add("is-invalid");
    const errorElement = inputElement.closest(".mb-3").querySelector(".invalid-feedback");
    if (errorElement) {
      errorElement.textContent = message;
      errorElement.style.display = 'block'; // Ensure it's visible
    }
  }

  function clearErrors() {
    loginForm.querySelectorAll(".is-invalid").forEach(input => {
      input.classList.remove("is-invalid");
    });
    formMessage.innerHTML = "";
    formMessage.className = "mb-3"; // Reset classes
  }
  
  function showFormMessage(message, type) {
    // Shows "Invalid username/password"
    formMessage.innerHTML = `<div class="alert alert-${type}">${message}</div>`;
  }
  
  function showToast(message, type = "error") {
    // Shows network errors
    const background = (type === "success")
      ? "linear-gradient(to right, #00b09b, #96c93d)" // Green
      : "linear-gradient(to right, #ff5f6d, #ffc371)"; // Red
      
    Toastify({
      text: message,
      duration: 3000,
      close: true,
      gravity: "top", 
      position: "right",
      style: { background: background }
    }).showToast();
  }

  function setButtonLoading(isLoading) {
    loginButton.disabled = isLoading;
    buttonText.style.display = isLoading ? "none" : "inline-block";
    loadingSpinner.style.display = isLoading ? "inline-block" : "none";
  }

  // === 3. Password Toggle ===
  togglePassword.addEventListener('click', () => {
    const type = passwordInput.getAttribute('type') === 'password' ? 'text' : 'password';
    passwordInput.setAttribute('type', type);
    togglePassword.classList.toggle('ph-eye');
    togglePassword.classList.toggle('ph-eye-slash');
  });
  
  // === 4. Client-side Validation ===
  function validateForm() {
    let isValid = true;
    clearErrors();

    if (identityInput.value.trim() === "") {
      showError(identityInput, "Please enter your username or email.");
      isValid = false;
    }
    
    if (passwordInput.value.trim() === "") {
      showError(passwordInput, "Please enter your password.");
      isValid = false;
    }
    
    return isValid;
  }

  // === 5. Submit Handler (AJAX) ===
  loginForm.addEventListener("submit", async (event) => {
    event.preventDefault();

    if (!validateForm()) {
      return; // Stop if client validation fails
    }

    setButtonLoading(true);

    const formData = {
      identity: identityInput.value.trim(),
      password: passwordInput.value.trim()
    };

    try {
      const response = await fetch('/login-backend', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json'
        },
        body: JSON.stringify(formData)
      });

      const data = await response.json();

      if (response.ok) {
        // --- SUCCESS ---
        // Server said login was good. Redirect.
        // The PHP script will send us where to go.
        window.location.href = data.redirect || '/home';
        
      } else {
        // --- AUTHENTICATION FAILED (401, 403) ---
        // Server said "Invalid credentials"
        showFormMessage(data.message, 'danger');
      }

    } catch (error) {
      // --- NETWORK/SERVER ERROR (500) ---
      console.error('Login failed:', error);
      showToast('Could not connect to the server. Please try again.', 'error');
    
    } finally {
      setButtonLoading(false);
    }
  });

});
</script>